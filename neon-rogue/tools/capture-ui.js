// 全界面截图巡检：输出到 shots/
const { chromium } = require('playwright'), path = require('path'); const ROOT = path.resolve(__dirname, '..');
const W = +process.env.W || 390, H = +process.env.H || 844;
(async () => {
  const b = await chromium.launch({ args: ['--no-sandbox'] }); const page = await b.newPage({ viewport: { width: W, height: H }, deviceScaleFactor: 1.5, isMobile: true, hasTouch: true });
  const errs = []; page.on('pageerror', e => errs.push(e.message));
  await page.addInitScript(() => { localStorage.setItem('neon-depth-mute', '1'); localStorage.setItem('neon-depth-meta', JSON.stringify({ cores: 640, up: { b1: 2, f1: 1, l1: 1 }, stash: { cyber: [{ id: 'eye_red', chips: [] }, { id: 'hand_purple', chips: [] }], chips: [] }, tickets: [] })); });
  await page.goto('file://' + path.join(ROOT, process.env.REL ? 'dist.html' : 'dist.debug.html'));
  const shot = async (n, fn, arg) => { if (fn) await page.evaluate(fn, arg); await page.waitForTimeout(450); await page.screenshot({ path: path.join(ROOT, 'shots', n + '.png') }); };
  await shot('01-menu');
  await shot('02-challenge', () => window.__neon.test.ui.challengeScreen());
  await shot('03-meta', () => window.__neon.test.ui.showMeta());
  await shot('04-market', () => window.__neon.test.ui.marketScreen('cyber'));
  await shot('05-stash', () => window.__neon.test.ui.marketScreen('stash'));
  await shot('06-prep', () => { window.__neon.G.classId = 'assault'; window.__neon.test.ui.prepScreen(); });
  await shot('07-rushprep', () => window.__neon.test.ui.rushPrepScreen());
  await page.evaluate(() => { const N = window.__neon, G = N.G; G.classId = 'assault'; N.startGame(); });
  await shot('08-start-skill');
  await page.evaluate(() => { const N = window.__neon; N.test.hideOverlay(); N.p.pending = 0; N.test.econ.maybeShowBoard(); });
  await shot('09-board');
  await page.evaluate(() => { const N = window.__neon, G = N.G; N.test.hideOverlay(); G.pendingBoard = null; G.paused = false; N.addConsumable(N.G && window.NEON.consumables[0]); N.addConsumable(window.NEON.consumables[8]); N.updateHUD(); });
  await shot('10-hud');
  await shot('11-cyber', () => window.__neon.test.ui.openCyber());
  await shot('12-item', () => { window.__neon.test.hideOverlay(); window.__neon.test.ui.openItemInfo(1); });
  await shot('13-reload', () => { window.__neon.test.hideOverlay(); window.__neon.test.ui.openReloadPicker(); });
  await shot('14-gun', () => { window.__neon.test.hideOverlay(); window.__neon.test.ui.openGun(); });
  await shot('15-menu-quests', () => { window.__neon.test.hideOverlay(); window.__neon.test.ui.openMenu('quests'); });
  await shot('16-codex', () => { window.__neon.test.ui.openMenu('codex'); document.querySelectorAll('details.cdx').forEach((d, i) => { if (i < 3) d.open = true; }); });
  await shot('17-help', () => window.__neon.test.ui.openMenu('help'));
  await shot('18-ach', () => window.__neon.test.ui.openMenu('ach'));
  await shot('19-skill', () => { const N = window.__neon; N.test.hideOverlay(); N.p.pending = 1; N.test.ui.showSkillChoice(); });
  await shot('20-evo', () => { const N = window.__neon; N.test.hideOverlay(); N.p.level = 5; N.test.ui.showEvolution(); });
  await shot('21-boon', () => { const N = window.__neon; N.test.hideOverlay(); N.G.pendingBoons = 1; N.test.ui.showBoonChoice(); });
  await page.evaluate(() => { const N = window.__neon, G = N.G; N.test.hideOverlay(); G.pendingBoons = 0; N.p.pending = 0; G.classId = 'engineer'; N.startGame(); N.test.hideOverlay(); N.p.pending = 0; G.pendingBoard = null; G.paused = false; G.scrap = 40; N.updateHUD(); });
  await shot('22-engineer-hud');
  await shot('23-build', () => window.__neon.test.ui.openBuild());
  await page.evaluate(() => { const N = window.__neon, G = N.G; N.test.hideOverlay(); G.classId = 'ghost'; N.startGame(); N.test.hideOverlay(); N.p.pending = 0; G.pendingBoard = null; G.paused = false; N.updateHUD(); });
  await shot('24-ghost-hud');
  await page.evaluate(() => { const N = window.__neon, G = N.G; N.test.hideOverlay(); G.classId = 'assault'; G.trainPending = true; N.startGame(); });
  await shot('25-train-gear');
  for (const t of ['chips', 'items', 'enemies', 'params']) await shot('26-train-' + t, (tt) => { const b = document.querySelector('[data-tr-panel="' + tt + '"]'); b && b.click(); }, t).catch(() => {});
  await page.evaluate(() => { const N = window.__neon, G = N.G; G.trainPending = false; N.test.hideOverlay(); G.classId = 'assault'; N.startGame(); N.test.hideOverlay(); G.state = 'over'; N.test.ui.endScreen(false, 1234, true); });
  await shot('27-end');
  console.log('errors', JSON.stringify(errs));
  await b.close();
})();
